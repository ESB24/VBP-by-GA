"""
    lb_std(ses::Session)

Compute a lower bound for a session smoothing algorithm using the standard deviation as fitness function.

First a vector `perfect_load` of the floored average value of each output is generated (perfectly smooth -> std = 0).
Then we add up to 1 to components of the `perfect_load` vector until it's sum equal the mail volume in session `ses`.
Now `std(perfect_load)` will have the smallest possible value, and `perfect_load` has the same load volume as session `ses`.
"""
function lb_std(ses::Session)

    O::Int64 = length(ses.load)
    mail_vol::Int64 = sum(ses.load)
    avg_vol::Float64 = mean(ses.load)

    floor_avg_vol::Float64 = floor(Int64, avg_vol)

    off_output::Int64 = mail_vol % O

    opt_load::Vector{Int64} = ones(Float64, O) .* floor_avg_vol

    opt_load[1:off_output] .+= 1

    return std(opt_load)
end


